function planFor(typeKey, domain) {
  if (typeKey === "review") return REVIEW_PLAN
  if (typeKey === "proposal" || typeKey === "task" || typeKey === "mid") return PROPOSAL_PLAN
  const short = new Set(["intern", "zhiji", "report", "homework", "reflection", "reading", "teaching", "career", "defense", "ppt"])
  if (short.has(typeKey)) return REPORT_PLAN
  const paper = new Set(["graduate", "journal", "title", "topic", "zb", "course", "monograph", "custom"])
  if (paper.has(typeKey)) return domain === "eng" ? ENG_PLAN : SOCIAL_PLAN
  return SOCIAL_PLAN
}

export function planOutline(typeKey, topic, _level = "三级大纲") {
  const domain = detectDomain(topic)
  const plan = planFor(typeKey, domain)
  const items = []
  plan.forEach((ch, ci) => {
    const chapterId = uid("c")
    items.push({ id: chapterId, level: 1, title: ch.t, role: ch.role || "chapter", domain, special: null })
    ch.subs.forEach((s, si) => {
      items.push({
        id: uid("c"),
        level: 2,
        title: s.t,
        role: s.role,
        parent: chapterId,
        no: `${ci + 1}.${si + 1}`,
      })
    })
  })
  items.push({ id: uid("c"), level: 1, title: "参考文献", special: "refs" })
  items.push({ id: uid("c"), level: 1, title: "致谢", special: "ack" })
  return items
}

