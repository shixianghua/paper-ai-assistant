function pickPool(pool, seed) {
  return pool[seed % pool.length]
}

function T(template, seed, topic) {
  const h = hashText(topic) + seed
  const pool = Array.isArray(template) ? template : [template]
  return pickPool(pool, h)
    .replaceAll("{t}", topic)
    .replaceAll("{T}", topic.replace(/^“|”$/g, ""))
}

